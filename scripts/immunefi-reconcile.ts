/**
 * Reproducible Immunefi reconciliation report (task 2).
 *
 *   npm run bounties:immunefi-reconcile          # fetch the live feed and regenerate docs/immunefi-reconciliation.md
 *
 * It checks robots.txt for the public-api path and REFUSES to fetch if disallowed (we never circumvent robots). This is a one-off
 * read-only analysis of the feed to account for every programme; it does NOT enable Immunefi collection — that adapter stays disabled
 * pending written Terms-of-Use confirmation (docs/source-access-decisions.md). The arithmetic lives in the pure, unit-tested
 * reconcileImmunefi(); this script only fetches and writes.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { reconcileImmunefi, renderReconciliationMarkdown } from "../apps/api/src/bounties/immunefi-reconcile.js";
import type { ImmunefiProgram } from "../apps/api/src/bounties/adapters.js";

const FEED = "https://immunefi.com/public-api/bounties.json";
const ROBOTS = "https://immunefi.com/robots.txt";
const OUT = fileURLToPath(new URL("../docs/immunefi-reconciliation.md", import.meta.url));

/** Minimal RFC 9309 check for the one path we fetch, for User-agent: * (the one group we obey). Refuses on any matching Disallow. */
function robotsAllows(robotsTxt: string, path: string): boolean {
  const lines = robotsTxt.split(/\r?\n/).map((l) => l.replace(/#.*$/, "").trim());
  let inStar = false; let sawStar = false; const disallows: string[] = [];
  for (const line of lines) {
    const m = /^(user-agent|disallow|allow)\s*:\s*(.*)$/i.exec(line);
    if (!m) continue;
    const [, field, value] = m;
    if (field!.toLowerCase() === "user-agent") { inStar = value!.trim() === "*"; if (inStar) sawStar = true; }
    else if (inStar && field!.toLowerCase() === "disallow" && value!.trim()) disallows.push(value!.trim());
  }
  if (!sawStar) return true; // no group addresses us
  return !disallows.some((d) => path.startsWith(d));
}

async function main(): Promise<void> {
  const robotsRes = await fetch(ROBOTS, { headers: { accept: "text/plain" } });
  if (robotsRes.ok) {
    const robotsTxt = await robotsRes.text();
    if (!robotsAllows(robotsTxt, "/public-api/bounties.json")) {
      console.error("robots.txt disallows /public-api/bounties.json — refusing to fetch. No report written.");
      process.exit(2);
    }
  } else {
    console.error(`could not read robots.txt (HTTP ${robotsRes.status}); refusing to fetch rather than assume permission.`);
    process.exit(2);
  }

  const res = await fetch(FEED, { headers: { accept: "application/json" } });
  if (!res.ok) { console.error(`feed HTTP ${res.status}`); process.exit(1); }
  const programs = (await res.json()) as ImmunefiProgram[];
  const r = reconcileImmunefi(programs, `${FEED} (fetched ${new Date().toISOString().slice(0, 10)})`);

  const header = [
    "<!-- Generated by scripts/immunefi-reconcile.ts (npm run bounties:immunefi-reconcile). Do not hand-edit the tables. -->",
    "",
    "## Why this report exists",
    "",
    "Task 2 asked for a *complete* reconciliation of the Immunefi public-api feed: account for every programme, explain why the",
    "GitHub-linked ones qualify, and discard nothing. An earlier note recorded \"~12 programmes with GitHub repositories\" — that figure",
    "came from the 12-programme **sample fixture** (`testing/fixtures/immunefi-public-api-2026-11-27.json.gz`, 10 of which are",
    "GitHub-linked), **not** the full feed. Reconciling the full feed below shows the real figure.",
    "",
    "**Immunefi collection remains DISABLED.** This is read-only analysis; the eligibility tiers are a *potential* (what Immunefi would",
    "contribute if enabled as an official source), not live system state. See the framing note under the eligibility table.",
    "",
    "The arithmetic is the pure, unit-tested `reconcileImmunefi()` (`apps/api/src/bounties/immunefi-reconcile.ts`,",
    "`immunefi-reconcile.test.ts`). The complete per-programme disposition is preserved in the function's `programmes[]` output (one row",
    "per raw record) so nothing is silently dropped; this document renders the summary.",
    "",
    "---",
    "",
  ].join("\n");

  writeFileSync(OUT, header + renderReconciliationMarkdown(r));
  console.log(`wrote ${OUT}: ${r.total_received} received, ${r.valid_parsed} valid, ${r.with_github_urls} GitHub-linked, checksum balances=${r.checksum.balances}`);
}

main().catch((e) => { console.error(e); process.exit(1); });
